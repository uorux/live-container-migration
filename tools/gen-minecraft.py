# The mc-whitelist ConfigMap's keys: whitelist.json-format lists and ops.json-format lists.
LISTS = ["backend.json", "global.json", "bmc.json", "ops-global.json", "ops-bmc.json"]


def whitelist_spec(root):
    """The gateways' -whitelist value: who may wake each pack (its whitelist plus its ops, as on a
    vanilla server). The most common pair becomes "*"."""
    pairs = {n: f"{root}/{wl}+{root}/{ops}" for n, _, _, _, wl, ops, _ in PACKS}
    common = max(set(pairs.values()), key=list(pairs.values()).count)
    return ",".join([f"*={common}"] + [f"{n}={v}" for n, v in pairs.items() if v != common])


def whitelist_configmaps(players):
    def entries(key):
        names = players.get(key.removesuffix(".json"), {})
        if key.startswith("ops-"):
            return [{"uuid": u, "name": n, "level": 4, "bypassesPlayerLimit": False} for n, u in names.items()]
        return [{"uuid": u, "name": n} for n, u in names.items()]
    data = {k: json.dumps(entries(k), indent=2) + "\n" for k in LISTS}
    # The servers copy theirs over /data at every start; the gateways re-read theirs within seconds.
    return [{"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "mc-whitelist", "namespace": ns},
             "data": data} for ns in ("minecraft", "minecraft-gw")]


# Every gateway the relays keep a session with: the in-cluster VIP gateways (one Service; standbys
# forward) and each VPS ingress box's tailnet address, port 7000 (deploy/standalone). A listed but
# unreachable gateway only logs reconnects (the tailnet ACL must allow nodes -> boxes tcp:7000).
GATEWAYS = [
    "lcm-gateway-vip-tunnel.minecraft-gw.svc.cluster.local:7001",
    "100.125.234.26:7000",  # aeon
    "100.92.154.30:7000",   # type-6a
]

HEADER = "# Generated by tools/gen-minecraft.py; edit that, not this.\n"


def livepod(name, req, lim, wl, ops, modded, image):
    relay = [
        "/lcm/lcm-relay", "run", "-gateway", ",".join(GATEWAYS), "-backend", name,
        "-token-file", "/secret/token", "-minecraft-ready",
        # No PROXY v2 parser in the images yet (sdfs/Paper can, once tested): players show as
        # 127.0.0.1 to the server; the gateways log the real addresses.
        "-proxy-protocol=false",
        "--", "/bin/mc-start",
    ]
    return {
        "apiVersion": "lcm.rooty.dev/v1alpha1",
        "kind": "LivePod",
        "metadata": {"name": name, "namespace": "minecraft"},
        "spec": {
            # Asleep until someone joins <name>.<domain> (or picks it in the menu); stopped
            # again after 10 minutes empty, like AutoServer's autoShutdownDelay on recusant.
            "onDemand": {"backend": name, "idleAfter": "10m", "startAsleep": True},
            "template": {
                "metadata": {"labels": {"app.kubernetes.io/part-of": "minecraft", "mc.rooty.dev/pack": name}},
                "spec": {
                    "runtimeClassName": "lcm",
                    "priorityClassName": "minecraft",
                    # The images are private (bundled mod licenses). Jacob creates this Secret
                    # outside git: dockerconfigjson for git.rooty.dev, a read-only package token.
                    # lcm forwards it to the destination node's pre-pull, so migrations pull
                    # before the freeze, not inside it.
                    "imagePullSecrets": [{"name": "minecraft-registry-pull"}],
                    # mc-start: `stop`, save (~2 s), SIGTERM to a lingering JVM after 25 s
                    # (MC_STOP_GRACE); exit 143 then is normal.
                    "terminationGracePeriodSeconds": 180,
                    "securityContext": {
                        "runAsUser": 1000, "runAsGroup": 1000, "fsGroup": 1000,
                        # Never chown a whole world at every start.
                        "fsGroupChangePolicy": "OnRootMismatch",
                    },
                    "initContainers": [{
                        "name": "fetch-relay",
                        "image": "busybox:1.37",
                        "command": ["sh", "-c", "wget -q -O /lcm/lcm-relay http://$HOST_IP:7790/v1/bin/lcm-relay && chmod +x /lcm/lcm-relay"],
                        "env": [{"name": "HOST_IP", "valueFrom": {"fieldRef": {"fieldPath": "status.hostIP"}}}],
                        "volumeMounts": [{"name": "lcm-bin", "mountPath": "/lcm"}],
                    }],
                    "containers": [{
                        "name": "mc",
                        "image": image,
                        "command": relay,
                        "resources": {
                            "requests": {"cpu": "2" if modded else "1", "memory": f"{req}Gi"},
                            "limits": {"memory": f"{lim}Gi"},
                        },
                        "ports": [
                            {"name": "mc-metrics", "containerPort": 19565},
                            {"name": "jmx", "containerPort": 9404},
                        ],
                        "volumeMounts": [
                            {"name": "data", "mountPath": "/data"},
                            {"name": "lcm-bin", "mountPath": "/lcm"},
                            {"name": "secret", "mountPath": "/secret", "readOnly": True},
                            {"name": "lists", "mountPath": "/etc/mc", "readOnly": True},
                        ],
                    }],
                    "volumes": [
                        {"name": "data", "persistentVolumeClaim": {"claimName": f"{name}-data"}},
                        {"name": "lcm-bin", "emptyDir": {}},
                        {"name": "secret", "secret": {"secretName": "lcm-tunnel"}},
                        # mc-start copies these over /data/{whitelist,ops}.json at every start, so the
                        # Secret is the source of truth: in-game /whitelist and /op last until a restart.
                        {"name": "lists", "configMap": {"name": "mc-whitelist", "items": [
                            {"key": wl, "path": "whitelist.json"},
                            {"key": ops, "path": "ops.json"},
                        ]}},
                    ],
                },
            },
        },
    }


def pvc(name, size):
    return {
        "apiVersion": "v1",
        "kind": "PersistentVolumeClaim",
        "metadata": {"name": f"{name}-data", "namespace": "minecraft",
                     "labels": {"app.kubernetes.io/part-of": "minecraft", "mc.rooty.dev/pack": name}},
        "spec": {
            "accessModes": ["ReadWriteMany"],
            "storageClassName": "ceph-filesystem",
            "resources": {"requests": {"storage": f"{size}Gi"}},
        },
    }


def backup_helper():
    # Velero backs up opt-in volumes of running pods; servers sleep most of the time and must not
    # carry the annotation (CRIU, and duplicate backups), so one idle pod mounts every world
    # read-only, as apps/infra/backup/rwx-backup-helpers.yaml does for gitea and librechat.
    names = [p[0] for p in PACKS]
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": "velero-backup-helper", "namespace": "minecraft", "labels": {"app": "velero-backup-helper"}},
        "spec": {
            "replicas": 1,
            "selector": {"matchLabels": {"app": "velero-backup-helper"}},
            "template": {
                "metadata": {"labels": {"app": "velero-backup-helper"},
                             "annotations": {"backup.velero.io/backup-volumes": ",".join(names)}},
                "spec": {
                    "securityContext": {"runAsUser": 1000, "runAsGroup": 1000},
                    "containers": [{
                        "name": "pause",
                        "image": "busybox:1.38",
                        "command": ["sh", "-c", "sleep infinity"],
                        "resources": {"requests": {"cpu": "5m", "memory": "8Mi"}, "limits": {"memory": "32Mi"}},
                        "volumeMounts": [{"name": n, "mountPath": f"/data/{n}", "readOnly": True} for n in names],
                    }],
                    "volumes": [{"name": n, "persistentVolumeClaim": {"claimName": f"{n}-data", "readOnly": True}} for n in names],
                },
            },
        },
    }


